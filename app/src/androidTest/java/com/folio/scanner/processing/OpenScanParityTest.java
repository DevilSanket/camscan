/** Expected coordinates are generated by the pinned, unchanged OpenScan Dart functions. */
@RunWith(AndroidJUnit4.class)
public class OpenScanParityTest {
  @BeforeClass
  public static void loadNativeLibraryForBaseline() {
    assertTrue(OpenCVLoader.initLocal());
  }

  @Test
  public void fixesFourReproducedMissesFromTheOriginalFolioDetector() throws Exception {
    JSONObject data;
    try (InputStream stream =
            InstrumentationRegistry.getInstrumentation()
                .getContext()
                .getAssets()
                .open("openscan/golden-fixtures.json");
        ByteArrayOutputStream bytes = new ByteArrayOutputStream()) {
      byte[] buffer = new byte[8192];
      int length;
      while ((length = stream.read(buffer)) != -1) bytes.write(buffer, 0, length);
      data = new JSONObject(bytes.toString(StandardCharsets.UTF_8.name()));
    }
    int checked = 0;
    JSONArray fixtures = data.getJSONArray("fixtures");
    for (int i = 0; i < fixtures.length(); i++) {
      JSONObject fixture = fixtures.getJSONObject(i);
      String name = fixture.getString("name");
      if (!name.equals("faint_page")
          && !name.equals("small_page")
          && !name.equals("narrow_receipt")
          && !name.equals("near_frame_page")) continue;
      int width = fixture.getInt("width"), height = fixture.getInt("height");
      byte[] pixels = Base64.decode(fixture.getString("grayBase64"), Base64.DEFAULT);
      Bitmap image = Bitmap.createBitmap(width, height, Bitmap.Config.ARGB_8888);
      try {
        int[] colors = new int[pixels.length];
        for (int p = 0; p < colors.length; p++) {
          int value = pixels[p] & 255;
          colors[p] = 0xff000000 | value << 16 | value << 8 | value;
        }
        image.setPixels(colors, 0, width, 0, 0, width, height);
        assertNull(name + " reproduced v1.0 miss", new LegacyV1DocumentProcessor().detect(image));
        assertNotNull(name + " now found", new DocumentProcessor().detect(image));
        System.out.println(
            "Detection regression " + name + ": v1.0 missed; OpenScan port detected");
        checked++;
      } finally {
        image.recycle();
      }
    }
    assertEquals(4, checked);
  }

  @Test
  public void matchesOriginalDartDetectorOnNineIndependentFixtures() throws Exception {
    JSONObject data;
    try (InputStream stream =
            InstrumentationRegistry.getInstrumentation()
                .getContext()
                .getAssets()
                .open("openscan/golden-fixtures.json");
        ByteArrayOutputStream bytes = new ByteArrayOutputStream()) {
      byte[] buffer = new byte[8192];
      int length;
      while ((length = stream.read(buffer)) != -1) bytes.write(buffer, 0, length);
      data = new JSONObject(bytes.toString(StandardCharsets.UTF_8.name()));
    }
    assertEquals("27bb7ab973fbb621fce182c43bc875856c785a30", data.getString("upstreamCommit"));
    JSONArray fixtures = data.getJSONArray("fixtures");
    assertEquals(9, fixtures.length());
    for (int index = 0; index < fixtures.length(); index++) {
      JSONObject fixture = fixtures.getJSONObject(index);
      String name = fixture.getString("name");
      int width = fixture.getInt("width"), height = fixture.getInt("height");
      byte[] pixels = Base64.decode(fixture.getString("grayBase64"), Base64.DEFAULT);
      OpenScanDetector.Result actual = OpenScanDetector.detectGrayscale(pixels, width, height);
      if (fixture.isNull("expectedCorners")) {
        assertNull(name, actual);
        continue;
      }
      assertNotNull(name, actual);
      JSONArray expected = fixture.getJSONArray("expectedCorners");
      for (int corner = 0; corner < 4; corner++) {
        assertEquals(
            name + " corner " + corner + " x",
            expected.getJSONArray(corner).getDouble(0),
            actual.points[corner].x,
            0.000001);
        assertEquals(
            name + " corner " + corner + " y",
            expected.getJSONArray(corner).getDouble(1),
            actual.points[corner].y,
            0.000001);
      }
      // Exercise the actual Android bitmap adapter and its source-pixel coordinate normalization.
      Bitmap photo = Bitmap.createBitmap(width, height, Bitmap.Config.ARGB_8888);
      try {
        int[] colors = new int[pixels.length];
        for (int i = 0; i < colors.length; i++) {
          int value = pixels[i] & 255;
          colors[i] = 0xff000000 | value << 16 | value << 8 | value;
        }
        photo.setPixels(colors, 0, width, 0, 0, width, height);
        DocumentProcessor.Detection detection = new DocumentProcessor().detect(photo);
        assertNotNull(name + " Android bitmap", detection);
        for (int corner = 0; corner < 4; corner++) {
          PointF point = detection.corners[corner];
          assertEquals(
              name + " normalized x", actual.points[corner].x / (width - 1), point.x, 0.000001);
          assertEquals(
              name + " normalized y", actual.points[corner].y / (height - 1), point.y, 0.000001);
        }
      } finally {
        photo.recycle();
      }
    }
  }

  @Test
  public void previousQuadBiasChoosesMatchingCandidateWithoutDroppingCorners() {
    byte[] mask = new byte[200 * 200];
    for (int y = 10; y < 60; y++) for (int x = 10; x < 90; x++) mask[y * 200 + x] = 1;
    for (int y = 120; y < 165; y++) for (int x = 120; x < 175; x++) mask[y * 200 + x] = 1;
    java.util.List<OpenScanDetector.P[]> candidates =
        OpenScanDetector.findCandidates(mask, 200, 200);
    OpenScanDetector.Result unbiased = OpenScanDetector.pickBest(candidates, 200, 200, null);
    assertTrue(unbiased.points[0].x < 100);
    OpenScanDetector.P[] previous = {
      new OpenScanDetector.P(120, 120),
      new OpenScanDetector.P(174, 120),
      new OpenScanDetector.P(174, 164),
      new OpenScanDetector.P(120, 164)
    };
    OpenScanDetector.Result tracked = OpenScanDetector.pickBest(candidates, 200, 200, previous);
    for (int i = 0; i < 4; i++) {
      assertEquals(previous[i].x, tracked.points[i].x, 0.000001);
      assertEquals(previous[i].y, tracked.points[i].y, 0.000001);
    }
  }
}
